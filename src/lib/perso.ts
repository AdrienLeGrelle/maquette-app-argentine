import type { Message } from './demo'

/**
 * Les longues discussions de la zone Perso : famille, fournisseurs, équipe.
 * Plusieurs jours d'échanges, pour qu'on sente un vrai téléphone qui défile.
 * `h` = le contact écrit, `o` = Hermine répond ; « # » ouvre une nouvelle journée.
 */
type Ligne = [qui: 'h' | 'o' | '#', heure: string, texte: string]

function fil(lignes: Ligne[]): Message[] {
  const messages: Message[] = []
  let jour: string | undefined
  for (const [qui, heure, texte] of lignes) {
    if (qui === '#') { jour = texte; continue }
    messages.push({ de: qui === 'h' ? 'huesped' : 'hotel', heure, texte, lu: qui === 'o' ? true : undefined, jour })
    jour = undefined
  }
  return messages
}

